import type { Account, PersonId } from './types'

/**
 * A lump-sum inflow or outflow at a specific age — an inheritance, a major expense
 * (a wedding, a new roof), estimated net proceeds from a home sale, etc. By default
 * fires in exactly the one projection year the owner turns `age`, not ongoing like a
 * pension — but `repeatEveryYears` turns it into a recurring expense (e.g. "a new
 * car every 10 years"), firing again at `age + repeatEveryYears`,
 * `age + 2*repeatEveryYears`, and so on through `repeatUntilAge` (or the plan's
 * horizon, if that's never set). Today's dollars, held flat like everything else in
 * this app except the mortgage — a repeated occurrence costs the same real amount
 * each time, not an inflated nominal one.
 */
export interface OneTimeEvent {
  id: string
  name: string
  /** The age (of `ownerId`) this event first occurs at. */
  age: number
  /** Whose age `age` refers to — defaults to the primary person when omitted. */
  ownerId?: PersonId
  /** Positive for an inflow, negative for an outflow. */
  amount: number
  /** Outflows only: repeats every this many years after `age` (e.g. `10` for "every
   * 10 years") instead of firing just once. Ignored for inflows — an inheritance
   * isn't something you'd model as recurring the same way an outflow can be. */
  repeatEveryYears?: number
  /** Outflows only, and only meaningful alongside `repeatEveryYears`: the last age
   * this can still recur at. Omit to let it keep recurring through the end of the
   * plan. */
  repeatUntilAge?: number
  /** Inflows only: counts as taxable ordinary income this year (e.g. a bonus) rather
   * than tax-free (e.g. most inheritances and gifts — the default, `false`).
   * Ignored for outflows. */
  taxable?: boolean
  /** Inflows only: which account receives the money — must be a taxable or cash
   * account (you can't just deposit outside money straight into a tax-advantaged
   * account). Ignored for outflows. An inflow with a missing or invalid target
   * simply isn't deposited anywhere — a documented no-op, same fallback convention
   * as an invalid RMD-surplus target (see `rmd.ts`). */
  targetAccountId?: string
}

/** True if `event` fires in the projection year `ageForOwner` was built for — i.e.
 * the event's own owner has, *this year* (not whatever age some other
 * caller-supplied variable happens to be — `ageForOwner` is already scoped to "this
 * year" by the caller, see `people.ts`'s `makeAgeForOwner`), either just reached
 * `age` (the one-time case) or landed on one of its recurrences (every
 * `repeatEveryYears` after that, through `repeatUntilAge` if set). */
function firesThisYear(event: OneTimeEvent, ageForOwner: (ownerId: PersonId) => number): boolean {
  const ownerAge = ageForOwner(event.ownerId ?? 'primary')
  if (ownerAge < event.age) return false

  // Recurrence is an outflow-only concept (see OneTimeEvent's own doc) — enforced
  // here, not just documented, so a stray repeatEveryYears on an inflow can't
  // accidentally make it recur.
  const isRepeating = event.amount < 0 && event.repeatEveryYears !== undefined && event.repeatEveryYears > 0
  if (!isRepeating) return ownerAge === event.age

  if (event.repeatUntilAge !== undefined && ownerAge > event.repeatUntilAge) return false
  return (ownerAge - event.age) % event.repeatEveryYears! === 0
}

/** Total one-time spending this year from outflow events (negative-amount events) —
 * added straight to spending need, same as any other expense. */
export function totalOneTimeOutflowForAge(events: OneTimeEvent[], ageForOwner: (ownerId: PersonId) => number): number {
  return events
    .filter((event) => event.amount < 0 && firesThisYear(event, ageForOwner))
    .reduce((total, event) => total + Math.abs(event.amount), 0)
}

export interface OneTimeInflowResult {
  balances: Record<string, number>
  taxableCostBasis: Record<string, number>
  /** Total taxable ordinary income generated by this year's inflow events (only
   * those marked `taxable`). */
  taxableOrdinaryIncome: number
  /** Total of every inflow event that fired this year (taxable or not), for display/transparency. */
  totalInflow: number
}

/**
 * Deposits this year's inflow events (positive-amount events) into their target
 * accounts — added directly to the account's balance (and cost basis, if the target
 * is a taxable account), same timing as a contribution: arrives this year, doesn't
 * compound until next. Because this runs *before* that year's withdrawal is solved,
 * a same-year expense can draw on newly-arrived cash if the target account is high
 * enough in the withdrawal order (taxable accounts are drawn first; a cash-account
 * target is drawn only as a last resort, by design — see `withdrawal.ts`) — you
 * choose the priority by choosing the target account.
 */
export function applyOneTimeInflows(
  events: OneTimeEvent[],
  ageForOwner: (ownerId: PersonId) => number,
  accounts: Account[],
  balances: Record<string, number>,
  taxableCostBasis: Record<string, number>,
): OneTimeInflowResult {
  const nextBalances = { ...balances }
  const nextTaxableCostBasis = { ...taxableCostBasis }
  let taxableOrdinaryIncome = 0
  let totalInflow = 0

  for (const event of events) {
    if (event.amount <= 0 || !firesThisYear(event, ageForOwner)) continue
    totalInflow += event.amount
    if (event.taxable) taxableOrdinaryIncome += event.amount

    const targetId = event.targetAccountId
    if (!targetId || !(targetId in nextBalances)) continue
    const targetAccount = accounts.find((account) => account.id === targetId)
    if (targetAccount?.type !== 'taxable' && targetAccount?.type !== 'cash') continue

    nextBalances[targetId] += event.amount
    if (targetAccount.type === 'taxable') {
      nextTaxableCostBasis[targetId] = (nextTaxableCostBasis[targetId] ?? 0) + event.amount
    }
  }

  return { balances: nextBalances, taxableCostBasis: nextTaxableCostBasis, taxableOrdinaryIncome, totalInflow }
}
